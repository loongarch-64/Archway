#ifndef ARCHWAY_PAGING_LAYOUT_H
#define ARCHWAY_PAGING_LAYOUT_H

#include <archway/memory_layout.h>

#define ARCHWAY_PHYSICAL_BITS 48
#define ARCHWAY_PAGE_SHIFT 12
#define ARCHWAY_PAGE_SIZE (1 << ARCHWAY_PAGE_SHIFT)
#define ARCHWAY_PT_INDEX_BITS 9
#define ARCHWAY_PT_ENTRY_SHIFT 3
#define ARCHWAY_PT_ENTRY_SIZE (1 << ARCHWAY_PT_ENTRY_SHIFT)
#define ARCHWAY_PT_L1_SHIFT (ARCHWAY_PAGE_SHIFT + ARCHWAY_PT_INDEX_BITS)
#define ARCHWAY_PT_L2_SHIFT (ARCHWAY_PT_L1_SHIFT + ARCHWAY_PT_INDEX_BITS)
#define ARCHWAY_PT_L3_SHIFT (ARCHWAY_PT_L2_SHIFT + ARCHWAY_PT_INDEX_BITS)
#define ARCHWAY_TLB_PAIR_SHIFT (ARCHWAY_PAGE_SHIFT + 1)
#define ARCHWAY_TLB_PAIR_ENTRY_SHIFT (ARCHWAY_PT_ENTRY_SHIFT + 1)

#endif
